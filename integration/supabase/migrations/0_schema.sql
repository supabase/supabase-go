-- Schema for the Go SDK integration tests, applied by Supabase stack start
-- before seed.sql.
-- RLS is enabled with an anonymous-read policy so the tests exercise the same
-- anon-role path a real consumer's publishable key uses.

create table public.instruments (
    id bigint generated by default as identity primary key,
    name text not null,
    acquired_year integer
);

alter table public.instruments enable row level security;

create policy "anonymous can read instruments"
    on public.instruments for select
    to anon
    using (true);

grant select on table public.instruments to anon;

create table public.players (
    id integer not null primary key,
    section integer not null,
    seat integer not null,
    rating integer,
    tenure integer
);

alter table public.players enable row level security;

create policy "anonymous can read players"
    on public.players for select
    to anon
    using (true);

grant select on table public.players to anon;
