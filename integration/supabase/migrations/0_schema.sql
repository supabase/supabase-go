-- before seed.sql.
-- RLS is enabled with an anonymous-read policy so the tests exercise the same
-- anon-role path a real consumer's publishable key uses.

create table public.instruments (
    id bigint generated by default as identity primary key,
    name text not null,
    acquired_year integer
